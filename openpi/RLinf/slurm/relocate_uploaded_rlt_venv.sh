#!/usr/bin/env bash
# Relocate the offline .venv-rlt archive from the Piper host to the cluster's
# shared home path. Run on the cluster login node after verifying archive hash.
set -euo pipefail

REPO_DIR="${RLINF_GPU_REPO_DIR:-$HOME/openpi/RLinf}"
ARCHIVE="${1:-$REPO_DIR/rlinf-venv-py311-torch260-cu124.tar.gz}"
VENV="$REPO_DIR/.venv-rlt"
OLD_REPO="/home/agilex/FluxVla/openpi/RLinf"
OLD_PY_HOME="/home/agilex/.local/share/uv/python/cpython-3.11-linux-x86_64-gnu/bin"
BASE_PY="$HOME/openpi/envs/pi0/bin/python3.11"
BASE_SITE="$HOME/openpi/envs/pi0/lib/python3.11/site-packages"

test -s "$ARCHIVE"
test -x "$BASE_PY"

if [[ -e "$VENV" ]]; then
  mv "$VENV" "$REPO_DIR/.venv-rlt.incomplete.$(date +%Y%m%d-%H%M%S)"
fi
tar -xzf "$ARCHIVE" -C "$REPO_DIR"

ln -sfn "$BASE_PY" "$VENV/bin/python"
ln -sfn python "$VENV/bin/python3"
ln -sfn python "$VENV/bin/python3.11"

sed -i \
  -e "s|^home = .*|home = $(dirname "$BASE_PY")|" \
  -e "s|^executable = .*|executable = $BASE_PY|" \
  "$VENV/pyvenv.cfg"

# Console entry points generated by uv contain the source machine's venv path.
while IFS= read -r script; do
  sed -i "1s|^#!${OLD_REPO}/.venv-rlt/bin/python[^ ]*|#!${VENV}/bin/python|" "$script"
done < <(grep -IlR "^#!${OLD_REPO}/.venv-rlt/bin/python" "$VENV/bin" || true)

# Repair the local-runtime bridge and RLinf editable-install mappings.
printf '%s\n' "$BASE_SITE" > "$VENV/lib/python3.11/site-packages/pi0_runtime.pth"
sed -i "s|${OLD_REPO}|${REPO_DIR}|g" \
  "$VENV/lib/python3.11/site-packages/__editable___rlinf_0_3_0_finder.py"
sed -i "s|${OLD_REPO}/.venv-rlt|${VENV}|g; s|${OLD_PY_HOME}|$(dirname "$BASE_PY")|g" \
  "$VENV/bin/activate" "$VENV/bin/activate.csh" "$VENV/bin/activate.fish" 2>/dev/null || true

export PYTHONPATH="$REPO_DIR"
"$VENV/bin/python" - <<'PY'
import openpi, ray, rlinf, torch, transformers
from transformers.models.siglip import check
print("openpi:", openpi.__file__)
print("rlinf:", rlinf.__file__)
print("ray:", ray.__version__)
print("torch:", torch.__version__, "CUDA available on login:", torch.cuda.is_available())
print("transformers:", transformers.__version__)
assert ray.__version__ == "2.56.0"
assert torch.__version__.split("+")[0] == "2.6.0"
assert transformers.__version__ == "4.53.2"
assert check.check_whether_transformers_replace_is_installed_correctly()
PY

if grep -RIl "/home/agilex/FluxVla/openpi/RLinf" \
  "$VENV/bin" "$VENV/lib/python3.11/site-packages" \
  --include='*.pth' --include='*.egg-link' --include='__editable__*finder.py' | grep -q .; then
  echo "Relocation left a source-repo absolute path behind." >&2
  exit 1
fi

echo "PASS: offline .venv-rlt relocated to $VENV"
